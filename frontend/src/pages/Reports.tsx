import { Bar, Line } from 'react-chartjs-2'
import type { ChartData, ChartOptions } from 'chart.js'
import { TopBar } from '../components/Layout'
import { CardHeader, Empty, Skeleton } from '../components/ui'
import { palette } from '../lib/chartSetup'
import { api } from '../lib/api'
import { fmtNum } from '../lib/format'
import { useStore } from '../lib/store'
import { usePoll } from '../hooks/hooks'

interface OeeTrend { series: { date: string; oee: number; availability: number; performance: number; quality: number }[]; note: string | null; timezone: string }
interface Downtime { rows: { date: string; shift: 'A' | 'B' | 'C'; downtime_min: number; stopped_min: number; idle_min: number }[]; total_by_shift: Record<string, number>; shifts: Record<string, string> }
interface MlAcc {
  yellow_alerts: number; with_feedback: number; true_positive: number; false_positive: number; precision: number | null; feedback_coverage: number | null
  offline_validation: { sample_precision: number; sample_recall: number; event_recall: number; faults_injected: number; faults_detected: number; false_alarm_samples_per_hour_on_healthy_machines: number } | null
  model: { trained_at?: string; algorithm?: string; training_rows?: number; training_data?: string }
}

export default function Reports() {
  const backfill = useStore((s) => s.config?.backfill)
  const trend = usePoll<OeeTrend>(() => api.get('/reports/oee-trend?days=7'), 30000)
  const down = usePoll<Downtime>(() => api.get('/reports/downtime?days=7'), 30000)
  const ml = usePoll<MlAcc>(() => api.get('/reports/ml-accuracy'), 10000)
  const c = palette()
  const base = { responsive: true, maintainAspectRatio: false, animation: { duration: 400 } } as const

  const t = trend.data
  const lineData: ChartData<'line'> | null = t && {
    labels: t.series.map((d) => d.date.slice(5)),
    datasets: [
      { label: 'OEE %', data: t.series.map((d) => d.oee), borderColor: c.accent, backgroundColor: 'rgba(34,211,238,.14)', fill: true, borderWidth: 3, tension: 0.3, pointRadius: 4 },
      { label: 'Availability %', data: t.series.map((d) => d.availability), borderColor: c.green, borderWidth: 1.5, borderDash: [5, 4], tension: 0.3, pointRadius: 0 },
      { label: 'Performance %', data: t.series.map((d) => d.performance), borderColor: c.accent2, borderWidth: 1.5, borderDash: [5, 4], tension: 0.3, pointRadius: 0 },
      { label: 'Quality %', data: t.series.map((d) => d.quality), borderColor: c.orange, borderWidth: 1.5, borderDash: [5, 4], tension: 0.3, pointRadius: 0 },
    ],
  }
  const lineOpts: ChartOptions<'line'> = {
    ...base,
    plugins: { legend: { labels: { color: c.text, usePointStyle: true, boxWidth: 10 } } },
    scales: { x: { grid: { color: c.grid }, ticks: { color: c.text } }, y: { min: 40, max: 100, grid: { color: c.grid }, ticks: { color: c.text, callback: (v) => `${v}%` } } },
  }

  const d = down.data
  const days = d ? [...new Set(d.rows.map((r) => r.date))] : []
  const shiftColor = { A: c.accent, B: c.accent2, C: c.orange } as const
  const barData: ChartData<'bar'> | null = d && {
    labels: days.map((x) => x.slice(5)),
    datasets: (['A', 'B', 'C'] as const).map((s) => ({
      label: `Shift ${s} (${d.shifts[s]})`,
      data: days.map((day) => d.rows.find((r) => r.date === day && r.shift === s)?.downtime_min ?? 0),
      backgroundColor: shiftColor[s], borderRadius: 4,
    })),
  }
  const barOpts: ChartOptions<'bar'> = {
    ...base,
    plugins: { legend: { labels: { color: c.text, usePointStyle: true, boxWidth: 10 } }, tooltip: { callbacks: { label: (x) => ` ${x.dataset.label}: ${x.parsed.y} min` } } },
    scales: { x: { grid: { display: false }, ticks: { color: c.text } }, y: { beginAtZero: true, grid: { color: c.grid }, ticks: { color: c.text, callback: (v) => `${v} min` } } },
  }

  const m = ml.data
  return (
    <div className="page">
      <TopBar title="Reports" sub="7-day OEE trend · downtime per shift · ML accuracy" />
      {backfill?.days ? <div className="card" style={{ padding: '12px 16px' }}><span className="muted" style={{ fontSize: 13 }}>
        History older than this session is <b style={{ color: 'var(--text)' }}>simulated</b> ({backfill.days} days generated by the virtual factory at start-up). In database mode, completed hours are persisted and survive restarts.</span></div> : null}

      <div className="grid g-2">
        <section className="card" aria-label="OEE trend">
          <CardHeader title="Daily OEE · last 7 days" icon="chart" />
          <div className="chart">{trend.loading && !t ? <Skeleton h={260} /> : trend.error ? <div className="err">{trend.error}</div> : t && t.series.length ? <Line data={lineData!} options={lineOpts} role="img" aria-label="Daily OEE for the last seven days" /> : <Empty title="No history yet" />}</div>
          {t && t.series.length > 0 && (
            <table className="tbl" style={{ marginTop: 12 }}>
              <thead><tr><th>Day</th><th>OEE</th><th>A</th><th>P</th><th>Q</th></tr></thead>
              <tbody>{t.series.slice().reverse().map((r) => (
                <tr key={r.date}><td className="mono">{r.date}</td><td className="mono"><b>{fmtNum(r.oee)}%</b></td><td className="mono">{fmtNum(r.availability)}</td><td className="mono">{fmtNum(r.performance)}</td><td className="mono">{fmtNum(r.quality)}</td></tr>
              ))}</tbody>
            </table>
          )}
        </section>

        <section className="card" aria-label="Downtime per shift">
          <CardHeader title="Downtime per shift · last 7 days" icon="clock" />
          <div className="chart">{down.loading && !d ? <Skeleton h={260} /> : down.error ? <div className="err">{down.error}</div> : d && d.rows.length ? <Bar data={barData!} options={barOpts} role="img" aria-label="Downtime minutes per shift per day" /> : <Empty title="No downtime data" />}</div>
          {d && (
            <div className="grid g-3" style={{ marginTop: 12 }}>
              {(['A', 'B', 'C'] as const).map((s) => (
                <div key={s} className="stack" style={{ gap: 2 }}>
                  <span className="lbl">Shift {s} · {d.shifts[s]}</span>
                  <b className="mono" style={{ fontSize: 22 }}>{fmtNum(d.total_by_shift[s], 0)} <span className="muted" style={{ fontSize: 12 }}>min</span></b>
                </div>
              ))}
            </div>
          )}
          <p className="faint" style={{ fontSize: 12, marginTop: 10 }}>Downtime = planned time − run time (stops plus micro-stops/idle), summed over all machines.</p>
        </section>
      </div>

      <section className="card" aria-label="ML accuracy">
        <CardHeader title="ML accuracy" icon="cpu" />
        {ml.loading && !m ? <Skeleton h={120} /> : m ? (
          <div className="grid g-2">
            <div className="stack">
              <div className="lbl">Operator feedback on Yellow cautions</div>
              <div className="row" style={{ gap: 26 }}>
                <div><b className="mono" style={{ fontSize: 34 }}>{m.precision === null ? '—' : `${(m.precision * 100).toFixed(0)}%`}</b><div className="muted" style={{ fontSize: 12 }}>precision (TP ÷ (TP+FP))</div></div>
                <div><b className="mono tag-ok" style={{ fontSize: 26 }}>{m.true_positive}</b><div className="muted" style={{ fontSize: 12 }}>true positives</div></div>
                <div><b className="mono tag-bad" style={{ fontSize: 26 }}>{m.false_positive}</b><div className="muted" style={{ fontSize: 12 }}>false positives</div></div>
              </div>
              <p className="muted" style={{ fontSize: 12.5 }}>
                {m.yellow_alerts} Yellow caution{m.yellow_alerts === 1 ? '' : 's'} raised, {m.with_feedback} with feedback.
                {m.with_feedback === 0 && ' Open the Alert centre and mark cautions with 👍 true / 👎 false positive to build this report.'}
              </p>
            </div>
            <div className="stack">
              <div className="lbl">Offline validation (injected faults, independent run)</div>
              {m.offline_validation ? (
                <dl className="kv">
                  <dt>Sample precision</dt><dd>{fmtNum(m.offline_validation.sample_precision * 100, 1)}%</dd>
                  <dt>Sample recall</dt><dd>{fmtNum(m.offline_validation.sample_recall * 100, 1)}%</dd>
                  <dt>Faults detected</dt><dd>{m.offline_validation.faults_detected} / {m.offline_validation.faults_injected}</dd>
                  <dt>False alarms / h (healthy)</dt><dd>{fmtNum(m.offline_validation.false_alarm_samples_per_hour_on_healthy_machines, 2)}</dd>
                  <dt>Model</dt><dd>{m.model.algorithm ? 'Isolation Forest' : '—'}</dd>
                  <dt>Trained on</dt><dd>{m.model.training_rows?.toLocaleString() ?? '—'} rows</dd>
                </dl>
              ) : <span className="muted">No validation metrics stored with this model.</span>}
            </div>
          </div>
        ) : <div className="err">{ml.error}</div>}
      </section>
    </div>
  )
}
